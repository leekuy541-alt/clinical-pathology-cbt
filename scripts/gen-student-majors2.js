const fs = require('fs');
const path = require('path');

function build(id, stem, correct, wrongs, explainCorrect, rot) {
  const choices = wrongs.slice(0, 4);
  const answerIndex = ((rot % 5) + 5) % 5;
  choices.splice(answerIndex, 0, correct);
  const ew = [];
  let wi = 0;
  for (let i = 0; i < 5; i++) {
    if (i === answerIndex) ew.push('');
    else ew.push((wrongs[wi] || '') + '은(는) 정답이 아니다.');
    if (i !== answerIndex) wi++;
  }
  return { id, stem, choices, answerIndex, explainCorrect, explainWrong: ew };
}
function write(name, arr) {
  fs.writeFileSync(path.join(__dirname, '..', 'data', name), JSON.stringify(arr, null, 2) + '\n');
  console.log('wrote', name, arr.length);
}
function split(prefix, rows) {
  const all = rows.map((r, i) => build(prefix + String(i + 1).padStart(2, '0'), r[0], r[1], r.slice(2, 6), r[6], i));
  write(prefix === 'he' ? 'he-part1.json' : prefix === 'it' ? 'it-part1.json' : 'mb-part1.json', all.slice(0, 50));
  write(prefix === 'he' ? 'he-part2.json' : prefix === 'it' ? 'it-part2.json' : 'mb-part2.json', all.slice(50));
}

