def main():
    p = Path("/workspace/clinical-pathology-cbt/data/practical.json")
    arr = json.loads(p.read_text(encoding="utf-8"))
    D = {r[0]: r for r in ROWS}
    missing = [q["id"] for q in arr if q["id"] not in D]
    extra = [k for k in D if k not in {q["id"] for q in arr}]
    if missing or extra:
        raise SystemExit(f"missing={missing} extra={extra}")
    for q in arr:
        _id, stem, correct, ws, ec, es = D[q["id"]]
        if len(ws) != 4 or len(es) != 4:
            raise SystemExit(f"{_id} wrongs/ews length")
        ai = q["answerIndex"]
        choices = list(ws)
        choices.insert(ai, correct)
        ew = list(es)
        ew.insert(ai, "")
        assert len(choices) == 5 and len(ew) == 5
        assert ew[ai] == ""
        q["stem"] = stem
        q["choices"] = choices
        q["explainCorrect"] = ec
        q["explainWrong"] = ew
        if not q.get("image"):
            raise SystemExit(f"{_id} missing image")
    p.write_text(json.dumps(arr, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("rewrote", len(arr), "practical items")

if __name__ == "__main__":
    main()
